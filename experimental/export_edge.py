"""
Exports everything the ESP32 needs into ./edge_demo/ :
  edge_params.h        feature indices, per-class mean / inverse covariance / limit, thresholds, scaler
  ae_model_data.h      the int8 TFLite model as a C array
  edge_test_vectors.h  raw windows + the answers Python expects (so the ESP32 can prove it matches)

  python export_edge.py
Run after edge_model.py, autoencoder.py and calibrate.py.
"""
import json
import os

import joblib
import numpy as np
import pandas as pd

import edge_model as em
from autoencoder import QuantAE
from features import extract_features
from train_model import assign_sessions

OUT = "edge_demo"


def fl(v):
    s = repr(float(np.float32(v)))
    if s in ("inf", "-inf", "nan"):
        raise ValueError("non-finite value in export")
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def vec(a):
    return "{" + ", ".join(fl(v) for v in a) + "}"


def mat(m):
    return "{" + ", ".join(vec(r) for r in m) + "}"


def make_vectors(stats, cols, qae, csv="training_data.csv"):
    df = assign_sessions(pd.read_csv(csv))
    cases = []
    for c in stats["classes"]:
        sub = df[df["label"] == c]
        sid = sub["session_id"].value_counts().idxmax()
        rd = sub[sub["session_id"] == sid].sort_values("timestamp")[["V", "I", "W", "PF", "Hz", "kWh"]].to_dict("records")
        for i in range(len(rd) // 2, len(rd) - 4):
            w = rd[i:i + 5]
            if all(r["W"] >= em.MIN_W for r in w):
                cases.append((c, w))
                break
    cases += [(c + "_x2", [{**r, "I": r["I"] * 2, "W": r["W"] * 2} for r in w]) for c, w in cases[:2]]
    out = []
    for name, w in cases:
        feats = np.array(extract_features(w))
        R, idx, _ = em.ratios(stats, feats[None, :])
        out.append((name, w, int(idx[0]), float(R[0]), float(qae.errors(feats[None, cols])[0])))
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    stats = joblib.load("edge_stats.pkl")
    meta = json.load(open("ae_meta.json"))
    try:
        cal = json.load(open("edge_calib.json"))
    except OSError:
        raise SystemExit("edge_calib.json missing: run calibrate.py first.")
    cols, names = stats["cols"], list(stats["classes"])
    k, n = len(cols), len(names)
    if meta["cols"] != cols:
        raise SystemExit("ae_meta.json was built for different features: rerun autoencoder.py.")

    h = ["// Generated by export_edge.py - do not edit by hand", "#pragma once", "#include <stdint.h>",
         f"#define EDGE_K {k}", f"#define EDGE_NCLASS {n}", f"#define EDGE_CONFIRM {int(cal['confirm'])}",
         f"#define EDGE_MIN_W {em.MIN_W}f",
         f"// features used: {', '.join(stats['names'])}",
         f"static const uint8_t EDGE_COLS[EDGE_K] = {{{', '.join(map(str, cols))}}};",
         "static const char* const EDGE_CLASS[EDGE_NCLASS] = {" + ", ".join(f'"{c}"' for c in names) + "};",
         "static const float EDGE_MEAN[EDGE_NCLASS][EDGE_K] = {" + ", ".join(vec(stats["classes"][c]["mean"]) for c in names) + "};",
         "static const float EDGE_INV[EDGE_NCLASS][EDGE_K][EDGE_K] = {" + ", ".join(mat(stats["classes"][c]["inv"]) for c in names) + "};",
         "static const float EDGE_THR[EDGE_NCLASS] = " + vec([stats["classes"][c]["thr"] for c in names]) + ";",
         f"static const float EDGE_MAH_LIMIT = {fl(cal['mah_limit'])};",
         f"static const float EDGE_AE_LIMIT = {fl(cal['ae_limit'])};",
         "static const float EDGE_AE_MU[EDGE_K] = " + vec(meta["mu"]) + ";",
         "static const float EDGE_AE_SD[EDGE_K] = " + vec(meta["sd"]) + ";", ""]
    open(f"{OUT}/edge_params.h", "w").write("\n".join(h))

    blob = open("ae_int8.tflite", "rb").read()
    rows = [", ".join(f"0x{b:02x}" for b in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    open(f"{OUT}/ae_model_data.h", "w").write(
        "// Generated by export_edge.py\n#pragma once\n"
        "alignas(16) const unsigned char ae_model_data[] = {\n  " + ",\n  ".join(rows) + "\n};\n"
        f"const unsigned int ae_model_len = {len(blob)};\n")

    tv = make_vectors(stats, cols, QuantAE())
    t = ["// Generated by export_edge.py", "#pragma once", "#include <stdint.h>", f"#define TV_N {len(tv)}",
         "static const char* const TV_NAME[TV_N] = {" + ", ".join(f'"{v[0]}"' for v in tv) + "};",
         "static const float TV_RAW[TV_N][5][4] = {" + ", ".join(
             "{" + ", ".join(vec([r["V"], r["I"], r["W"], r["PF"]]) for r in v[1]) + "}" for v in tv) + "};",
         "static const int8_t TV_NEAREST[TV_N] = {" + ", ".join(str(v[2]) for v in tv) + "};",
         "static const float TV_MAH[TV_N] = " + vec([v[3] for v in tv]) + ";",
         "static const float TV_AE[TV_N] = " + vec([v[4] for v in tv]) + ";", ""]
    open(f"{OUT}/edge_test_vectors.h", "w").write("\n".join(t))

    print(f"Wrote edge_params.h, ae_model_data.h ({len(blob)} bytes), edge_test_vectors.h into ./{OUT}/")
    print(f"Classes (index order): {names}")
    print(f"Limits: mah {cal['mah_limit']:.3f}, ae {cal['ae_limit']:.4f}")
    print(f"Next: put edge_ai.h and edge_demo.ino in ./{OUT}/ and open edge_demo.ino in the Arduino IDE.")


if __name__ == "__main__":
    main()